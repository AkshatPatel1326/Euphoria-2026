export type EventCategory = "cultural" | "literary-management" | "science-tech" | "sports" | "test";

export type RegistrationType = "individual" | "group";
export type PaymentStatus = "pending" | "success" | "failed" | "cancelled";
export type ParticipantCategory = "sage" | "other-college" | "general";

export interface CoordinatorItem {
  name: string;
  phone: string;
}

export interface EuphoriaEvent {
  id: string;
  name: string;
  category: EventCategory;
  description: string;
  poster: string | null;

  /* ── Backend-ready fields ── */
  fee: number;
  registrationType: RegistrationType;
  minTeamSize: number;
  maxTeamSize: number;
  registrationOpen: boolean;

  /* ── Display fields (may be superseded by backend data) ── */
  registrationFee: string;
  date: string;
  day: string;
  time: string;
  venue: string;
  teamSize: string;
  prizes: string;
  rules: string;

  /* ── Coordinator fields ── */
  facultyCoordinator?: string;
  studentCoordinator?: string;
  facultyCoordinators?: CoordinatorItem[];
  studentCoordinators?: CoordinatorItem[];

  /* ── Event Family / Stage / Variant relationship ── */
  eventFamily?: string;
  variant?: "solo" | "group" | "single" | "double" | "1-dress" | "6-dress" | string;
  stage?: "audition" | "main" | "finalist";
  capacity?: number;
  activeRegistrationsCount?: number;
  status?: "DRAFT" | "PUBLISHED" | "COMPLETED" | "CANCELLED";
}

